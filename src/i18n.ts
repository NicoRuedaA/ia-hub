export type TranslationKey = keyof typeof dictionaries.en
type InterpolationValue = string | number

export function translate(language: Language, key: TranslationKey, values: Record<string, InterpolationValue> = {}): string {
  const dictionary = dictionaries[language ?? 'en']
  const template = dictionary[key] ?? dictionaries.en[key] ?? key
  return template.replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(values[name] ?? ''))
}

export function languageName(language: Language, selected: UiLanguage): string {
  return translate(language, selected === 'en' ? 'language.english' : 'language.spanish')
}

export function useTranslation() {
  const language = usePreferencesStore((state) => state.language)
  return { language, t: (key: TranslationKey, values?: Record<string, InterpolationValue>) => translate(language, key, values) }
}
